/**
 * A live, entirely code-rendered 3D ASCII head.
 *
 * Geometry: parametric curved head (including ears, neck and glasses), rotated in
 * three dimensions and perspective-projected onto a character-cell z-buffer.
 * Appearance: samples only the user's authentic, existing portrait photo at
 * runtime for tonal differences. No generated imagery, video or GIF is used.
 *
 * Each glyph has a fixed canvas coordinate. Unlike the old SVG <text> portrait,
 * this cannot reflow or stretch if browser fonts differ on Vercel.
 */
(() => {
  'use strict';
  const SOURCE = 'assets/media/photos/01-identity-restaurant-portrait-original-photograph.webp';
  const RAMP = '.,:;-+=*#%@';
  const TAU = Math.PI * 2;
  const portrait = new Image();
  let pixels = null, sourceWidth = 0, sourceHeight = 0;
  const points = [];
  const clamp = (n, lo, hi) => Math.max(lo, Math.min(hi, n));

  portrait.onload = () => {
    const sample = document.createElement('canvas');
    sample.width = 400;
    sample.height = 420;
    const context = sample.getContext('2d', {willReadFrequently:true});
    // The crop is deliberately derived from the real uploaded portrait, not
    // from a generated facial image or an inferred likeness.
    context.drawImage(portrait, 160, 60, 448, 405, 0, 0, sample.width, sample.height);
    pixels = context.getImageData(0, 0, sample.width, sample.height).data;
    sourceWidth = sample.width;
    sourceHeight = sample.height;
  };
  portrait.onerror = () => { pixels = null; };
  portrait.src = SOURCE;

  function toneAt(u, v) {
    if (!pixels) return {value:.53, edge:.20};
    const x = clamp(Math.round(u * (sourceWidth - 1)), 2, sourceWidth - 3);
    const y = clamp(Math.round(v * (sourceHeight - 1)), 2, sourceHeight - 3);
    const lum = (xx, yy) => {
      const at = (yy * sourceWidth + xx) * 4;
      return (pixels[at] * .26 + pixels[at+1] * .65 + pixels[at+2] * .09) / 255;
    };
    const mid = lum(x,y);
    const edge = clamp((Math.abs(lum(x-2,y)-lum(x+2,y)) + Math.abs(lum(x,y-2)-lum(x,y+2)))*1.65,0,1);
    return {value: mid, edge};
  }

  const profile = [
    [-1.29,.31],[-1.20,.43],[-1.08,.58],[-.97,.67],[-.76,.80],[-.47,.92],
    [-.12,1.00],[.25,1.01],[.61,.94],[.91,.79],[1.10,.60],[1.27,.24],[1.32,.04]
  ];
  function radiusAt(y) {
    for (let i=1; i<profile.length; i++) {
      if (y <= profile[i][0]) {
        const [a,ra] = profile[i-1], [b,rb] = profile[i];
        return ra + (rb-ra) * (y-a)/(b-a);
      }
    }
    return .04;
  }
  // World coordinates: +Z is the face, +Y is the crown of the head.
  // Store parameters, not pixels, so all artwork is genuinely generated by code.
  for (let iy=0; iy<=95; iy++) {
    const y = -1.29 + iy/95*2.61;
    const radius = radiusAt(y);
    for (let ia=0; ia<168; ia++) {
      const a = ia / 168 * TAU;
      const front = Math.cos(a) > .04;
      const x = radius * Math.sin(a);
      const z = radius * Math.cos(a) * .76;
      // x/y refer to the source photo's facial features; the projected surface
      // itself is genuinely curved in 3D, not a flat card rotation.
      const u = clamp(.5 + Math.sin(a)*.39,0,1);
      const v = clamp((1.32-y)/2.61,0,1);
      const wobble = Math.sin(iy*5.1+ia*1.8)*.006;
      points.push([x+wobble,y,z,front?u:-1,v,front?1:0,0]);
    }
  }
  // Small procedural ears on both sides of the 3D head.
  for(const sign of [-1,1]) for(let i=0;i<27;i++) for(let k=0;k<13;k++) {
    const a=i/26*TAU, v=k/12;
    const x=sign*(.98+.11*Math.cos(a)*Math.sin(v*Math.PI));
    const y=-.21+(v-.5)*.47;
    const z=.02+.10*Math.sin(a)*Math.sin(v*Math.PI);
    points.push([x,y,z,-1,0,0,1]);
  }
  // Neck, positioned behind the chin, with no separate photo graphic.
  for(let i=0;i<34;i++)for(let j=0;j<48;j++) {
    const a=j/48*TAU,y=-1.25-i/33*.37;
    const x=.33*Math.sin(a), z=.30*Math.cos(a)-.13;
    points.push([x,y,z,-1,0,0,2]);
  }
  // 3D ASCII glasses. Small character points follow a curved front surface.
  // They are geometric, not a pasted face texture or bitmap outline.
  function frontZ(x){return .76*Math.sqrt(Math.max(0,1-(x/.99)**2))+.043;}
  for(const sign of [-1,1]) {
    const left=sign<0?-.73:.08, right=sign<0?-.08:.73;
    for(let i=0;i<=35;i++){
      const x=left+(right-left)*(i/35);
      points.push([x,.035,frontZ(x),-1,0,0,3]);
      points.push([x,-.34,frontZ(x),-1,0,0,3]);
    }
    for(let i=0;i<=20;i++){
      const y=.035-(.375*i/20);
      points.push([left,y,frontZ(left),-1,0,0,3]);
      points.push([right,y,frontZ(right),-1,0,0,3]);
    }
  }
  for(let i=0;i<=19;i++){
    const x=-.08+i/19*.16;
    points.push([x,-.08,frontZ(x),-1,0,0,3]);
  }
  function render(ctx, width, height, time) {
    ctx.clearRect(0,0,width,height);
    const mobile = width < 680;
    const scroll = clamp(window.scrollY / Math.max(450,window.innerHeight),0,1);
    const cx = mobile ? width*.52 : width*(.718 + .07*scroll);
    const cy = mobile ? height*.38 : height*(.44 - .05*scroll);
    const scale = (mobile ? Math.min(width*.31,height*.205) : Math.min(width*.215,height*.294))*(1-.53*scroll);
    const cellW=mobile?7.1:8.2;
    const cellH=cellW*1.35;
    const cols = Math.ceil(width/cellW)+1;
    const rows = Math.ceil(height/cellH)+1;
    const depths = new Float32Array(cols*rows);depths.fill(-Infinity);
    const glyphs = new Array(cols*rows);
    const inks = new Float32Array(cols*rows);
    const types = new Uint8Array(cols*rows);
    const rotation = time * .215; // One complete revolution ~29 seconds.
    const c=Math.cos(rotation),s=Math.sin(rotation);
    const pitch=-.045;
    const cp=Math.cos(pitch),sp=Math.sin(pitch);
    const cameraZ=3.7;
    for(let n=0;n<points.length;n++){
      const p=points[n], x=p[0],y=p[1],z=p[2];
      const X = x*c + z*s;
      const Z = -x*s + z*c;
      const Y = y*cp-Z*sp;
      const D = y*sp+Z*cp;
      const perspective = cameraZ/(cameraZ-D*.30);
      const px=cx+X*scale*perspective;
      const py=cy-Y*scale*perspective;
      const ix=Math.round(px/cellW),iy=Math.round(py/cellH);
      if(ix<1||ix>=cols-1||iy<1||iy>=rows-1)continue;
      const idx=iy*cols+ix;
      if(D<=depths[idx])continue;
      const kind=p[6];
      const lit=clamp(.48+.45*(z*c-x*s)+.06*y,.18,1);
      let density, alpha;
      if(kind===0 && p[5]===1){
        const t=toneAt(p[3],p[4]);
        // Inverting source luminance preserves distinctive dark hair and glasses.
        density=clamp(.15+.73*(1-t.value)+t.edge*.48,.05,.98);
        alpha=clamp((.38+.62*density)*lit+.08,.16,.98);
      }else if(kind===3){density=.96;alpha=clamp(.92*lit+.22,.36,1);}
      else if(kind===1){density=.65;alpha=clamp(.62*lit,.21,.86);}
      else if(kind===2){density=.29;alpha=clamp(.45*lit,.12,.62);}
      else{ // Back of the head: slightly variegated, darker than the face.
        const hair= y>.15;
        density=(hair?.70:.34)+.17*Math.sin(y*14+x*30);
        alpha=clamp((hair?.56:.35)*lit+.13,.14,.77);
      }
      const char = RAMP[clamp(Math.floor(density*(RAMP.length-1)),0,RAMP.length-1)];
      if(!char)continue;
      depths[idx]=D+(kind===3?.018:0);
      glyphs[idx]=char;
      inks[idx]=alpha;
      types[idx]=kind;
    }
    ctx.textAlign='center';ctx.textBaseline='middle';
    ctx.font=`${(cellW*1.33).toFixed(2)}px "Courier New",monospace`;
    // Batch fillStyle changes by quantizing opacity, but each glyph remains its
    // own precisely positioned cell in a depth-tested 3D surface.
    for(let i=0;i<glyphs.length;i++){
      if(!glyphs[i])continue;
      const a=(Math.round(inks[i]*8)/8).toFixed(3);
      const kind=types[i];
      ctx.fillStyle=kind===3?`rgba(195,255,145,${a})`:kind===2?`rgba(139,190,136,${a})`:`rgba(226,245,218,${a})`;
      ctx.fillText(glyphs[i],(i%cols)*cellW,Math.floor(i/cols)*cellH);
    }
  }
  window.ABHI_PORTRAIT_3D={render,source:SOURCE};
})();
